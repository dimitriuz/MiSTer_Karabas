#!/usr/bin/env bash
# The one-command build of the MiSTer core: regenerate build/upstream/ from
# the submodule, run the upstream-change tripwire, compile with Quartus in
# Docker, then gate the result with tools/check_timing.py (negative slack
# in the TimeQuest summary, a missing clk_bus28/clk_bus24 clock or an sdc
# warning naming Karabas_Profi.sdc fail the build: Quartus exits 0 with
# timing unclosed). The last line is always `build: exit <code>`, so a
# detached poller
#   setsid nohup tools/build.sh </dev/null >build/logs/build.log 2>&1 &
#   for i in $(seq 1 30); do sleep 60; grep -q '^build: exit' build/logs/build.log && break; done
# Quartus rewrites LAST_QUARTUS_VERSION in Karabas_Profi.qsf; revert it after
# a successful build (see README). The build_id.v date stamp is generated by
# the flow itself (sys/sys.tcl PRE_FLOW_SCRIPT_FILE -> sys/build_id.tcl).
set -uo pipefail
cd "$(dirname "$0")/.."

python3 tools/prepare_upstream.py && tools/check_upstream.sh && tools/qbuild.sh . Karabas_Profi \
    && python3 tools/check_timing.py output_files
code=$?
echo "build: exit $code"
exit "$code"
