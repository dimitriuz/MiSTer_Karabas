#!/usr/bin/env bash
# The upstream gate: prove tools/prepare_upstream.py --profile elab still yields a
# tree Quartus 17 can analyse and elaborate. Writes build/elab/elab.qpf/.qsf
# (family Cyclone V, device 5CSEBA6U23I7, top `profi`, the unisim stub, the
# generated upstream.qip and a generated `clock` stub: the upstream entity copied
# verbatim, an architecture driving every clock output from CLK, every enable
# '1', ARESET '0') and runs quartus_map --analysis_and_elaboration in
# raetro/quartus:17.0 (Docker, repo mounted, host uid — as tools/qbuild.sh does).
# The last line is always `elab_upstream: exit <code>`; exits with that code.
set -euo pipefail
cd "$(dirname "$0")/.."

if [ $# -ne 0 ]; then
    echo "usage: tools/elab_upstream.sh" >&2
    echo "elab_upstream: exit 2"
    exit 2
fi

cleanup() {
    local c=$?
    echo "elab_upstream: exit $c"
}
trap cleanup EXIT

: "${QUARTUS_IMAGE:=raetro/quartus:17.0}"

python3 tools/prepare_upstream.py --profile elab --out build/elab/upstream

mkdir -p build/elab

SRC=upstream/karabas-go-core-profi/src/rtl/clock/clock.vhd
printf 'library ieee;\nuse ieee.std_logic_1164.all;\n\n' > build/elab/clock_stub.vhd
sed -n '/^entity clock is/,/end clock;/p' "$SRC" >> build/elab/clock_stub.vhd
grep -q '^entity clock is' build/elab/clock_stub.vhd || {
    echo "elab_upstream: could not extract the clock entity from $SRC" >&2; false; }
python3 - build/elab/clock_stub.vhd <<'PY'
import re, sys
text = open(sys.argv[1]).read()
ports = re.findall(r'(\w+)\s*:\s*(in|out|buffer)\s+std_logic', text)
lines = ["architecture stub of clock is", "begin"]
for name, direction in ports:
    if direction == "in":
        continue
    if name == "ARESET":
        value = "'0'"
    elif name.upper().startswith("CLK"):
        value = "CLK"
    else:  # ENA_*, CE_*
        value = "'1'"
    lines.append(f"  {name} <= {value};")
lines += ["end architecture;", ""]
open(sys.argv[1], "a").write("\n".join(lines))
PY

cat > build/elab/elab.qsf <<'EOF'
# generated by tools/elab_upstream.sh — the upstream analysis/elaboration gate
set_global_assignment -name FAMILY "Cyclone V"
set_global_assignment -name DEVICE 5CSEBA6U23I7
set_global_assignment -name TOP_LEVEL_ENTITY profi
set_global_assignment -name VHDL_FILE ../../rtl/compat/unisim_vcomponents.vhd -library unisim
set_global_assignment -name VHDL_FILE clock_stub.vhd
set_global_assignment -name QIP_FILE upstream/upstream.qip
EOF
printf 'PROJECT_REVISION = "elab"\n' > build/elab/elab.qpf

set +e
docker run --rm \
    -v "$PWD":/work -w /work/build/elab \
    -u "$(id -u):$(id -g)" -e HOME=/tmp \
    "$QUARTUS_IMAGE" \
    quartus_map elab --analysis_and_elaboration
exit $?
